//Запросіть у користувача його ім'я та виведіть у відповідь «Привіт, (його ім'я)!».
let userName = prompt("Введіть ваше ім'я:");
alert("Привіт " + userName + "!");

//Запросіть у користувача довжину сторони квадрата та виведіть його периметр.
let side = prompt("Введіть довжину сторони квадрата:");
let perimeter = Number(side) * 4;
alert("Периметр квадрата: " + perimeter);

//Запросіть у користувача радіус кола та виведіть його площу.
let radius = prompt("Введіть радіус кола:");
let area = Math.PI * Math.pow(Number(radius), 2);
alert("Площа кола: " + area.toFixed(2));
//використала toFixed для округлення числа

//Запросіть у користувача відстань у кілометрах між двома містами та за скільки годин він хоче дістатися. 
// Порахуйте швидкість, з якою потрібно рухатися, щоб встигнути вчасно.
let distance = prompt("Введіть відстань у км між містами:");
let hours = prompt("За скільки годин хочете дістатися?");
let speed = Number(distance) / Number(hours);
alert("Потрібна швидкість: " + speed.toFixed(2) + " км/год");

//Користувач вводить суму грошей у гаманці та вартість однієї шоколадки. 
// Програма виводить скільки шоколадок може купити користувач і скільки здачі в нього залишиться.
let money = prompt("Скільки грошей у гаманці?");
let chocolatePrice = prompt("Скільки коштує одна шоколадка?");
let chocolates = Math.floor(Number(money) / Number(chocolatePrice));
let change = Number(money) % Number(chocolatePrice);
alert("Можна купити " + chocolates + " шоколадок. Здача: " + change + " грн");

//Запросіть у користувача його рік народження, підрахуйте скільки йому років і виведіть результат. 
// Поточний рік вкажіть у коді як константу.
const YEAR = 2026;
let birthYear = prompt("Введіть ваш рік народження:");
let age = YEAR - Number(birthYear);
alert("Вам " + age + " років");